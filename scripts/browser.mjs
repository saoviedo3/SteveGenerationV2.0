function run(command, args, extraEnv = {}) {
  const result = spawnSync(command, args, { env: { ...env, ...extraEnv }, encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`${command} falló: ${result.stderr}\n${result.stdout}`);
}
